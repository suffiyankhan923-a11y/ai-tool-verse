import { createClient, SupabaseClient } from '@supabase/supabase-js';
import { Tool, Blog, Category, FAQ } from '../types/index.js';

const STORAGE_KEY_URL = 'toolverse_supabase_url';
const STORAGE_KEY_ANON = 'toolverse_supabase_anon_key';

let cachedClient: SupabaseClient | null = null;
let currentConfig = {
  url: '',
  anonKey: ''
};

export function isValidSupabaseUrl(url: unknown): boolean {
  if (!url || typeof url !== 'string') return false;
  const trimmed = url.trim();
  if (!trimmed.startsWith('https://') && !trimmed.startsWith('http://')) return false;
  try {
    const parsed = new URL(trimmed);
    return (parsed.protocol === 'https:' || parsed.protocol === 'http:') && Boolean(parsed.hostname);
  } catch {
    return false;
  }
}

export function getSupabaseConfig(): { url: string; anonKey: string; isEnv: boolean } {
  const metaEnv = (import.meta as any).env || {};
  const envUrl = (metaEnv.VITE_SUPABASE_URL || '').trim();
  const envKey = (metaEnv.VITE_SUPABASE_ANON_KEY || '').trim();

  if (isValidSupabaseUrl(envUrl) && envKey) {
    return { url: envUrl, anonKey: envKey, isEnv: true };
  }

  try {
    const localUrl = (localStorage.getItem(STORAGE_KEY_URL) || '').trim();
    const localKey = (localStorage.getItem(STORAGE_KEY_ANON) || '').trim();
    if (isValidSupabaseUrl(localUrl) && localKey) {
      return { url: localUrl, anonKey: localKey, isEnv: false };
    }
  } catch {
    // Ignore localStorage errors
  }

  return { url: '', anonKey: '', isEnv: false };
}

export function saveSupabaseConfig(url: string, anonKey: string): void {
  const cleanUrl = url.trim();
  const cleanKey = anonKey.trim();

  if (isValidSupabaseUrl(cleanUrl) && cleanKey) {
    localStorage.setItem(STORAGE_KEY_URL, cleanUrl);
    localStorage.setItem(STORAGE_KEY_ANON, cleanKey);
  } else {
    localStorage.removeItem(STORAGE_KEY_URL);
    localStorage.removeItem(STORAGE_KEY_ANON);
  }
  cachedClient = null; // Invalidate client to recreate with new credentials
}

export function clearSupabaseConfig(): void {
  try {
    localStorage.removeItem(STORAGE_KEY_URL);
    localStorage.removeItem(STORAGE_KEY_ANON);
  } catch {
    // ignore
  }
  cachedClient = null;
}

export function getSupabaseClient(): SupabaseClient | null {
  const config = getSupabaseConfig();
  
  if (!isValidSupabaseUrl(config.url) || !config.anonKey) {
    return null;
  }

  // Check if we can reuse cached instance
  if (cachedClient && currentConfig.url === config.url && currentConfig.anonKey === config.anonKey) {
    return cachedClient;
  }

  try {
    currentConfig = { url: config.url, anonKey: config.anonKey };
    cachedClient = createClient(config.url, config.anonKey, {
      auth: {
        persistSession: true,
        autoRefreshToken: true,
        detectSessionInUrl: true,
        storageKey: 'toolverse_supabase_auth_token'
      }
    });
    return cachedClient;
  } catch (err) {
    console.warn('Failed to initialize Supabase client:', err);
    return null;
  }
}

export async function testSupabaseConnection(url: string, anonKey: string): Promise<{ success: boolean; message: string }> {
  try {
    const cleanUrl = (url || '').trim();
    const cleanKey = (anonKey || '').trim();

    if (!cleanUrl || !cleanKey) {
      return { success: false, message: 'Please provide both Project URL and Anon API Key' };
    }

    if (!isValidSupabaseUrl(cleanUrl)) {
      return { success: false, message: 'Supabase URL must be a valid HTTP or HTTPS URL (e.g., https://your-project.supabase.co)' };
    }

    const testClient = createClient(cleanUrl, cleanKey, {
      auth: { persistSession: false }
    });

    // Test reachability and API key validity via session lookup
    const { error } = await testClient.auth.getSession();
    if (error && !error.message.includes('Auth session missing')) {
      return { success: false, message: error.message };
    }

    return { success: true, message: 'Connected to Supabase successfully!' };
  } catch (err: any) {
    return { success: false, message: err.message || 'Could not connect to Supabase endpoint.' };
  }
}


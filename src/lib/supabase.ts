/**
 * Pushes local database data (categories, tools, blogs, faqs) to Supabase tables
 */
export async function pushDataToSupabase(data: {
  categories: Category[];
  tools: Tool[];
  blogs: Blog[];
  faqs: FAQ[];
}): Promise<{ success: boolean; message: string; details?: any }> {
  const client = getSupabaseClient();
  if (!client) {
    return { success: false, message: 'Supabase client is not configured.' };
  }

  try {
    let syncedCats = 0;
    let syncedTools = 0;
    let syncedBlogs = 0;
    let syncedFaqs = 0;

    // 1. Categories
    if (data.categories.length > 0) {
      const catPayload = data.categories.map(c => ({
        name: c.name,
        slug: c.slug,
        description: c.description,
        icon: c.icon || 'Folder',
        color: c.color || '#B5824C'
      }));
      const { error: catError } = await client.from('categories').upsert(catPayload, { onConflict: 'slug' });
      if (catError) {
        throw new Error(`Categories sync error: ${catError.message}. Did you run the SQL schema script in Supabase?`);
      }
      syncedCats = data.categories.length;
    }

    // 2. Tools
    if (data.tools.length > 0) {
      const toolsPayload = data.tools.map(t => ({
        name: t.name,
        slug: t.slug,
        short_description: t.short_description,
        full_description: t.full_description,
        category: t.category,
        keywords: t.keywords,
        faq: typeof t.faq === 'string' ? JSON.parse(t.faq || '[]') : t.faq || [],
        icon: t.icon || 'Sparkles',
        featured: t.featured || 0,
        trending: t.trending || 0,
        usage_count: t.usage_count || 0
      }));
      const { error: toolsError } = await client.from('tools').upsert(toolsPayload, { onConflict: 'slug' });
      if (toolsError) {
        throw new Error(`Tools sync error: ${toolsError.message}`);
      }
      syncedTools = data.tools.length;
    }

    // 3. Blogs
    if (data.blogs.length > 0) {
      const blogsPayload = data.blogs.map(b => ({
        title: b.title,
        slug: b.slug,
        excerpt: b.excerpt,
        content: b.content,
        category: b.category,
        author: b.author || 'ToolVerse Editorial Team',
        cover_image: b.cover_image || b.featured_image,
        reading_time: b.reading_time || '5 min read',
        tags: b.tags,
        published: b.published ?? 1
      }));
      const { error: blogsError } = await client.from('blogs').upsert(blogsPayload, { onConflict: 'slug' });
      if (blogsError) {
        throw new Error(`Blogs sync error: ${blogsError.message}`);
      }
      syncedBlogs = data.blogs.length;
    }

    // 4. FAQs
    if (data.faqs.length > 0) {
      const faqsPayload = data.faqs.map(f => ({
        question: f.question,
        answer: f.answer,
        category: f.category
      }));
      const { error: faqsError } = await client.from('faqs').upsert(faqsPayload);
      if (faqsError) {
        throw new Error(`FAQs sync error: ${faqsError.message}`);
      }
      syncedFaqs = data.faqs.length;
    }

    return {
      success: true,
      message: `Successfully synced ${syncedCats} categories, ${syncedTools} tools, ${syncedBlogs} articles, and ${syncedFaqs} FAQs to your Supabase project!`,
      details: { syncedCats, syncedTools, syncedBlogs, syncedFaqs }
    };
  } catch (err: any) {
    return {
      success: false,
      message: err.message || 'Failed to sync data to Supabase.'
    };
  }
}

/**
 * Fetches all database entities from Supabase tables
 */
export async function fetchDataFromSupabase(): Promise<{
  categories: Category[];
  tools: Tool[];
  blogs: Blog[];
  faqs: FAQ[];
} | null> {
  const client = getSupabaseClient();
  if (!client) return null;

  try {
    const [catsRes, toolsRes, blogsRes, faqsRes] = await Promise.all([
      client.from('categories').select('*').order('id', { ascending: true }),
      client.from('tools').select('*').order('id', { ascending: true }),
      client.from('blogs').select('*').order('id', { ascending: false }),
      client.from('faqs').select('*').order('id', { ascending: true })
    ]);

    if (catsRes.error || toolsRes.error || blogsRes.error || faqsRes.error) {
      return null;
    }

    return {
      categories: (catsRes.data || []) as Category[],
      tools: (toolsRes.data || []).map(t => ({
        ...t,
        faq: typeof t.faq === 'object' ? JSON.stringify(t.faq) : t.faq
      })) as Tool[],
      blogs: (blogsRes.data || []) as Blog[],
      faqs: (faqsRes.data || []) as FAQ[]
    };
  } catch {
    return null;
  }
}
